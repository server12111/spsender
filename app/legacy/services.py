    async def _act_mutual_ping(self, account: Account, client) -> bool:
        """Start a ~20-message chat (in the background) with an account from
        the admin's warmup pool — up to _WARMUP_DIALOG_PER_DAY a day, each with
        a different partner, preferring ones it hasn't talked to (or not for
        the longest), so over a few days it talks to many accounts."""
        now_mono = time.monotonic()
        hour = now_moscow().hour
        if not (_WARMUP_DIALOG_HOURS[0] <= hour < _WARMUP_DIALOG_HOURS[1]):
            return False
        times = [t for t in self._dialog_times.get(account.id, []) if now_mono - t < 86400]
        self._dialog_times[account.id] = times
        per_day = min(_WARMUP_DIALOG_PER_DAY, max(1, self._day_index.get(account.id, _WARMUP_DIALOG_PER_DAY)))
        if len(times) >= per_day or (times and now_mono - max(times) < _WARMUP_DIALOG_MIN_GAP):
            return False
        try:
            pool = {aid for aid, _ in await self.db.get_warmup_partners()}
            if account.id in pool or self.is_frozen(account.id):
                return False  # pool accounts are company for clients' accounts, not for each other
            # A pool account can hold several chats at once; others one.
            cap = lambda aid: _WARMUP_POOL_CONCURRENT if aid in pool else 1
            if self._dialog_busy.get(account.id, 0) >= cap(account.id):
                return False
            candidates = list(pool)
            for sib in await self.db.get_user_accounts(account.user_id):
                if sib.is_active and sib.id != account.id:
                    w = await self.db.get_warmup(sib.id)
                    if w and w.enabled:
                        candidates.append(sib.id)
            candidates = [aid for aid in dict.fromkeys(candidates)
                          if aid != account.id and not self.is_frozen(aid) and self._dialog_busy.get(aid, 0) < cap(aid)
                          and frozenset((account.id, aid)) not in self._dialog_active]
        except Exception:
            return False
        if not candidates:
            return False
        history = self._dialog_partners.setdefault(account.id, {})
        random.shuffle(candidates)
        candidates.sort(key=lambda aid: history.get(aid, -1e18))  # never talked to first, then the oldest
        partner = partner_client = None
        for partner_id in candidates[:3]:
            partner = await self.db.get_account(partner_id)
            partner_client = await self.userbot_manager.get_client(partner_id) if partner else None
            if partner_client:
                break
        if not partner_client:
            return False
        for aid in (account.id, partner.id):
            self._dialog_busy[aid] = self._dialog_busy.get(aid, 0) + 1
        self._dialog_active.add(frozenset((account.id, partner.id)))
        times.append(now_mono)
        history[partner.id] = now_mono
        task = asyncio.create_task(self._run_dialog(account, client, partner, partner_client))
        self._dialog_tasks.add(task)
        task.add_done_callback(self._dialog_tasks.discard)
        return True

    async def _resume_dialogs(self):
        """A restart used to cut every running chat mid-word — a question left
        hanging, half the chats of the day lost. They go on where they were."""
        queue, self._resume_queue = self._resume_queue, []
        resumed = 0
        for prog in queue:
            try:
                a, b = await self.db.get_account(prog["a"]), await self.db.get_account(prog["b"])
                if not a or not b or not a.is_active or not b.is_active or self.is_frozen(a.id) or self.is_frozen(b.id):
                    continue
                pair = frozenset((a.id, b.id))
                if pair in self._dialog_active:
                    continue
                a_client = await self.userbot_manager.get_client(a.id)
                b_client = await self.userbot_manager.get_client(b.id) if a_client else None
                if not b_client:
                    continue
                for aid in (a.id, b.id):
                    self._dialog_busy[aid] = self._dialog_busy.get(aid, 0) + 1
                self._dialog_active.add(pair)
                task = asyncio.create_task(self._run_dialog(a, a_client, b, b_client, resume=prog))
                self._dialog_tasks.add(task)
                task.add_done_callback(self._dialog_tasks.discard)
                resumed += 1
                await asyncio.sleep(random.uniform(1, 5))
            except Exception as e:
                logger.warning(f"Warmup: resuming chat {prog.get('a')}<->{prog.get('b')} failed: {e}")
        if queue:
            logger.info(f"Warmup: resumed {resumed} of {len(queue)} chats cut off by the restart")

    async def _run_dialog(self, a: Account, a_client, b: Account, b_client, resume: Optional[dict] = None):
        from telethon.tl.functions.contacts import ImportContactsRequest
        from telethon.tl.functions.messages import SetTypingRequest
        from telethon.tl.types import InputPhoneContact, SendMessageTypingAction

        pair = None
        cur_acc = a  # whose request is in flight — a freeze error belongs to it
        pair_key = f"{min(a.id, b.id)}-{max(a.id, b.id)}"
        progress: Optional[dict] = None
        try:
            async def _peer(client, other: Account):
                nonlocal cur_acc
                cur_acc = a if client is a_client else b
                res = await client(ImportContactsRequest([
                    InputPhoneContact(client_id=random.randint(1, 2**31), phone=other.phone,
                                      first_name=_contact_name(cur_acc.id, other.id), last_name=""),
                ]))
                user = pick_imported_user(res, getattr(self.userbot_manager, "_me_ids", {}).get(other.id), other.phone)
                if user is None:
                    logger.warning(f"Warmup dialog: contact import of {other.id} on {cur_acc.id} gave no matching user: "
                                   f"{[(u.id, getattr(u, 'bot', None)) for u in res.users]}")
                return user

            a_peer, b_peer = await _peer(a_client, b), await _peer(b_client, a)
            if not a_peer or not b_peer:
                return
            # Their messages to each other mustn't trigger autoresponders/notifications.
            pair = frozenset((a_peer.id, b_peer.id))
            self._pair_refs[pair] = self._pair_refs.get(pair, 0) + 1
            self.userbot_manager._warmup_pairs.add(pair)
            sides = [(a, a_client, a_peer), (b, b_client, b_peer)]
            if (resume["first"] != a.id) if resume else random.random() < 0.5:
                sides.reverse()  # the partner writes first — incoming chats count too
            guard = ChatGuard()

            def _mark(acc_id, res):
                guard.mark(acc_id, res)
                if progress is not None:
                    progress["done"] = progress["pos"]  # this script line went out
            for _acc, cl, pr in sides:
                await guard.intruded(_acc.id, cl, pr)  # baseline: what's in the chat before we start

            async def _intruded() -> bool:
                # The owner typed into this chat from one of the accounts: stop
                # the script so nobody "answers" or quotes a real message.
                for _acc, cl, pr in sides:
                    if await guard.intruded(_acc.id, cl, pr):
                        logger.info(f"Warmup dialog {a.id}<->{b.id}: a person wrote from {_acc.id}, dialog stopped")
                        return True
                return False

            async def _hide_chat():
                # Muted + archived on both sides: muted archived chats stay in
                # the archive when new messages arrive.
                from telethon.tl.functions.account import UpdateNotifySettingsRequest
                from telethon.tl.types import InputNotifyPeer, InputPeerNotifySettings
                for _acc, cl, pr in sides:
                    try:
                        await cl(UpdateNotifySettingsRequest(
                            peer=InputNotifyPeer(await cl.get_input_entity(pr)),
                            settings=InputPeerNotifySettings(mute_until=2**31 - 1),
                        ))
                        await cl.edit_folder(pr, 1)
                    except (FloodWaitError, PeerFloodError):
                        raise
                    except Exception as e:
                        logger.warning(f"Warmup dialog: mute/archive failed for {_acc.id}: {e}")

            sent = 0
            prev_speaker = None
            voice_sent = False
            # Now and then the chat starts with a call nobody takes (a couple a
            # week per warming account): one side rings, the other declines or
            # misses it, then they text about it.
            if (not resume and random.random() < 0.3 and self._day_index.get(a.id, 99) >= _WARMUP_CALLS_FROM_DAY
                    and await self.calls.can_call(a.id)):
                from .warmup_calls import AFTER_DECLINED, AFTER_MISSED
                caller, callee = (0, 1) if random.random() < 0.5 else (1, 0)
                c_acc, c_client, c_peer = sides[caller]
                r_acc, r_client, _ = sides[callee]
                outcome = await self.calls.place(c_acc, c_client, r_acc, r_client, c_peer)
                if outcome:
                    first, second = AFTER_DECLINED if outcome == "declined" else AFTER_MISSED
                    await asyncio.sleep(random.uniform(20, 120) if outcome == "declined" else random.uniform(60, 400))
                    for spk, txt in ((callee, random.choice(first)), (caller, random.choice(second))):
                        s_acc, s_client, s_peer = sides[spk]
                        try:
                            await s_client.send_read_acknowledge(s_peer)
                        except Exception:
                            pass
                        await asyncio.sleep(random.uniform(1.5, 2.5) + len(txt) * random.uniform(0.08, 0.2))
                        _mark(s_acc.id, await s_client.send_message(s_peer, txt))
                        sent += 1
                        await asyncio.sleep(random.uniform(*_WARMUP_DIALOG_GAP))
                    prev_speaker = caller
                    await _hide_chat()
            fwd_sent = False
            voice_topic = None
            photo_sent_topic = None
            if resume:
                script = [(spk, _wd_item_load(x)) for spk, x in resume["script"]]
                start = resume["pos"] + (1 if resume.get("done") == resume["pos"] else 0)
                sent = resume.get("sent", 0)
                prev_speaker = script[start - 1][0] if 0 < start <= len(script) else None
                dumped = resume["script"]
            else:
                last = self._pair_topics.get(pair_key)
                followup = None
                if last and 3 * 3600 < time.time() - last[0] < 5 * 86400 and random.random() < 0.6:
                    options = [t for t in last[1] if t in _WD_FOLLOWUPS]
                    followup = random.choice(options) if options else None
                topics: list = []
                script = _warmup_dialog_script(followup=followup, topics_out=topics)
                self._pair_topics[pair_key] = (time.time(), topics)
                start = 0
                dumped = [[spk, _wd_item_dump(x)] for spk, x in script]
            progress = {"a": a.id, "b": b.id, "first": sides[0][0].id, "script": dumped,
                        "pos": start, "done": None, "sent": sent, "ts": time.time()}
            self._dialog_progress[pair_key] = progress
            for pos in range(start, len(script)):
                speaker, text = script[pos]
                progress.update(pos=pos, sent=sent, ts=time.time())
                acc, client, peer = sides[speaker]
                cur_acc = acc
                if sent and await _intruded():
                    break
                if _WARMUP_NIGHT_START_HOUR <= now_moscow().hour < _WARMUP_NIGHT_END_HOUR:
                    # Midnight: they say goodbye and go quiet until the morning.
                    if sent:
                        for spk, txt in ((speaker, random.choice(_WD_CLOSERS[0])),
                                         (1 - speaker, random.choice(_WD_CLOSERS[1]))):
                            s_acc, s_client, s_peer = sides[spk]
                            cur_acc = s_acc
                            await asyncio.sleep(random.uniform(1.5, 2.5) + len(txt) * random.uniform(0.08, 0.2))
                            _mark(s_acc.id, await send_text(s_client, s_peer, txt))
                            sent += 1
                            await asyncio.sleep(random.uniform(*_WARMUP_DIALOG_GAP))
                    break
                if isinstance(text, VoiceReply):
                    if not voice_sent:
                        continue  # the voice note was skipped (daily cap / no files)
                    voice_sent = False
                    vmsg = None
                    if (random.random() < 0.25 and self._day_index.get(acc.id, 99) >= _WARMUP_VOICES_FROM_DAY
                            and (vmsg := await self.voices.send(client, peer, acc.id, voice_topic or "generic")) is not None):
                        _mark(acc.id, vmsg)
                        sent += 1  # answered with a voice note too
                        prev_speaker = speaker
                        await asyncio.sleep(random.uniform(*_WARMUP_DIALOG_GAP))
                        continue
                    text = random.choice(VOICE_REPLIES)
                if isinstance(text, ForwardReply):
                    if not fwd_sent:
                        continue
                    fwd_sent = False
                    text = random.choice(FORWARD_REPLIES)
                if isinstance(text, PhotoReply):
                    if not photo_sent_topic:
                        continue
                    text = random.choice(PHOTO_REPLIES.get(photo_sent_topic, ["класс"]))
                    photo_sent_topic = None
                if prev_speaker is not None and prev_speaker != speaker and isinstance(text, str) and sent >= 4:
                    r = random.random()
                    if r < 0.015:
                        # Got distracted: answers 10-40 min later, with an apology.
                        await asyncio.sleep(random.uniform(600, 2400))
                        if _WARMUP_NIGHT_START_HOUR <= now_moscow().hour < _WARMUP_NIGHT_END_HOUR:
                            break
                        try:
                            await client.send_read_acknowledge(peer)
                        except Exception:
                            pass
                        await asyncio.sleep(random.uniform(2, 5))
                        guard.mark(acc.id, await send_text(client, peer, random.choice(AWAY_SORRY)))  # not the line itself
                        sent += 1
                        await asyncio.sleep(random.uniform(3, 10))
                    elif r < 0.065:
                        await hesitate(client, peer)  # starts typing, stops, comes back to it
                if prev_speaker is not None and prev_speaker != speaker:
                    try:
                        await client.send_read_acknowledge(peer)
                    except Exception:
                        pass
                    if random.random() < 0.12:
                        # A reaction on what the other side just wrote, before answering.
                        if await _intruded():
                            break  # never react to what a person wrote
                        target = await last_incoming_id(client, peer)
                        if target:
                            await react(client, peer, target)
                            await asyncio.sleep(random.uniform(1, 4))
                if isinstance(text, VoiceNote):
                    voice_topic = text.topic
                    vmsg = None
                    voice_sent = (self._day_index.get(acc.id, 99) >= _WARMUP_VOICES_FROM_DAY
                                  and (vmsg := await self.voices.send(client, peer, acc.id, text.topic)) is not None)
                    if voice_sent:
                        _mark(acc.id, vmsg)
                        sent += 1
                        prev_speaker = speaker
                        await asyncio.sleep(random.uniform(*_WARMUP_DIALOG_GAP))
                    continue
                if isinstance(text, PhotoNote):
                    pmsg = None
                    if (self._day_index.get(acc.id, 99) >= _WARMUP_VOICES_FROM_DAY
                            and (pmsg := await self.photos.send(client, peer, acc.id, text.topic)) is not None):
                        _mark(acc.id, pmsg)
                        photo_sent_topic = text.topic
                        sent += 1
                        prev_speaker = speaker
                        await asyncio.sleep(random.uniform(*_WARMUP_DIALOG_GAP))
                    continue
                if isinstance(text, ForwardNote):
                    fmsg = await forward_post(client, peer)
                    fwd_sent = fmsg is not None
                    if fwd_sent:
                        _mark(acc.id, fmsg)
                        sent += 1
                        prev_speaker = speaker
                        await asyncio.sleep(random.uniform(3, 12))
                        _mark(acc.id, await send_text(client, peer, random.choice(FORWARD_COMMENTS)))
                        sent += 1
                        await asyncio.sleep(random.uniform(*_WARMUP_DIALOG_GAP))
                    continue
                if isinstance(text, StickerNote):
                    await asyncio.sleep(random.uniform(2, 5))  # picking one
                    smsg = await send_sticker(client, peer, acc.id, text)
                    if smsg is not None:
                        _mark(acc.id, smsg)
                        sent += 1
                        prev_speaker = speaker
                        await asyncio.sleep(random.uniform(*_WARMUP_DIALOG_GAP))
                        continue
                    text = text.fallback  # no sticker — the short reply as text
                try:
                    await client(SetTypingRequest(peer, SendMessageTypingAction()))
                except (FloodWaitError, PeerFloodError):
                    raise
                except Exception:
                    pass
                await asyncio.sleep(random.uniform(1.5, 2.5) + len(text) * random.uniform(0.08, 0.2))
                reply_to = None
                if prev_speaker is not None and prev_speaker != speaker and random.random() < 0.1:
                    if await _intruded():
                        break  # a person wrote while this side was "typing" — never quote it
                    reply_to = await last_incoming_id(client, peer)
                _mark(acc.id, await send_text(client, peer, text, reply_to=reply_to))
                sent += 1
                prev_speaker = speaker
                if sent == 2:
                    await _hide_chat()  # both sides have the chat now
                await asyncio.sleep(random.uniform(*_WARMUP_DIALOG_GAP))
            await _hide_chat()
            logger.info(f"Warmup dialog {a.id}<->{b.id}: {sent} messages")
        except (FloodWaitError, PeerFloodError) as e:
            wait_s = getattr(e, "seconds", None) or config.PEER_FLOOD_COOLDOWN_SECONDS
            logger.warning(f"Warmup dialog {a.id}<->{b.id} stopped: {type(e).__name__}")
            for acc in (a, b):
                try:
                    await self.db.set_flood_wait_until(acc.id, now_moscow() + timedelta(seconds=min(wait_s, 21600)))
                except Exception:
                    pass
        except Exception as e:
            self.note_error(cur_acc.id, e)
            logger.warning(f"Warmup dialog {a.id}<->{b.id} stopped: {type(e).__name__}: {e}")
        finally:
            if not self._stopping or self._dialog_progress.get(pair_key) is not progress:
                self._dialog_progress.pop(pair_key, None)  # finished/broken — only a shutdown keeps the place
            if pair is not None:
                # Keep the pair silenced a while longer: a late-delivered
                # message must not hit the autoresponder either.
                asyncio.get_running_loop().call_later(6 * 3600, self._release_pair, pair)
            self._dialog_active.discard(frozenset((a.id, b.id)))
            for aid in (a.id, b.id):
                left = self._dialog_busy.get(aid, 1) - 1
                if left > 0:
                    self._dialog_busy[aid] = left
                else:
                    self._dialog_busy.pop(aid, None)

    def _release_pair(self, pair) -> None:
        left = self._pair_refs.get(pair, 1) - 1
        if left > 0:
            self._pair_refs[pair] = left
        else:
            self._pair_refs.pop(pair, None)
            self.userbot_manager._warmup_pairs.discard(pair)

