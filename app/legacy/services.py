def _wd_item_dump(x) -> list:
    """A script slot as JSON (the place in a running chat is saved for restarts)."""
    if isinstance(x, str):
        return ["t", x]
    if isinstance(x, VoiceNote):
        return ["v", x.topic]
    if isinstance(x, PhotoNote):
        return ["p", x.topic]
    if isinstance(x, StickerNote):
        return ["s", x.emoji, x.fallback]
    return [{VoiceReply: "vr", PhotoReply: "pr", ForwardNote: "f", ForwardReply: "fr"}[type(x)]]

def _wd_item_load(d: list):
    k = d[0]
    if k == "t":
        return d[1]
    if k == "v":
        return VoiceNote(d[1])
    if k == "p":
        return PhotoNote(d[1])
    if k == "s":
        return StickerNote(d[1], d[2])
    return {"vr": VoiceReply, "pr": PhotoReply, "f": ForwardNote, "fr": ForwardReply}[k]()

def _warmup_dialog_script(followup: Optional[str] = None, topics_out: Optional[list] = None) -> list[tuple[int, str]]:
    """(speaker 0/1, text) — a casual chat of roughly 20-30 messages built
    from several coherent topic threads. Up to two voice-note slots
    (VoiceNote on the thread's topic + a VoiceReply answer) may follow threads."""
    target = random.randint(*_WARMUP_DIALOG_MESSAGES)  # threads cap it at what fits without repeats
    if random.random() < 0.4:
        target = random.randint(6, 20)  # a quick exchange, as most real chats are
    lines = [(0, random.choice(_WD_OPENERS)), (1, random.choice(_WD_GREETS))]
    if followup in _WD_FOLLOWUPS:
        for i, variants in enumerate(_WD_FOLLOWUPS[followup]):
            lines.append((i % 2, random.choice(variants)))
    opener = 1
    voice_slots = 0
    forwarded = False
    photo_done = False
    for thread in random.sample(_WD_THREADS, len(_WD_THREADS)):
        if len(lines) >= target - 2:
            break
        if topics_out is not None:
            topics_out.append(topic_of(thread))
        for i, variants in enumerate(thread):
            text = random.choice(variants)
            lines.append(((opener + i) % 2, maybe_sticker(text) if len(text) <= 3 else text))
        if voice_slots < 2 and random.random() < 0.2:
            sp = random.randint(0, 1)
            lines.append((sp, VoiceNote(topic_of(thread))))
            lines.append((1 - sp, VoiceReply()))
            voice_slots += 1
        elif random.random() < 0.3:
            lines.append(((opener + len(thread)) % 2, maybe_sticker(random.choice(_WD_FILLERS))))
        pt = photo_topic(topic_of(thread))
        if pt and not photo_done and random.random() < 0.12:
            # A photo on the thread's topic with a caption, the other side reacts.
            sp = random.randint(0, 1)
            lines.append((sp, PhotoNote(pt)))
            lines.append((1 - sp, PhotoReply()))
            photo_done = True
        if not forwarded and random.random() < 0.025:  # ~1 dialog in 3
            # A channel post forwarded with a comment, the other side reacts.
            sp = random.randint(0, 1)
            lines.append((sp, ForwardNote()))
            lines.append((1 - sp, ForwardReply()))
            forwarded = True
        opener = 1 - opener
    lines.append((0, random.choice(_WD_CLOSERS[0])))
    lines.append((1, random.choice(_WD_CLOSERS[1])))
    return lines

class WarmupService:
    """Account warmup tool — human-like activity simulation so a fresh or
    idle account looks organic before/while it's used for mailing/parsing.
    Deliberately has zero interaction with MailingService/ParserService: it
    only reads the shared Telethon client via userbot_manager.get_client()
    (same connection, not a separate one) and never touches mailing_targets/
    parser_settings state, so an account can be warmed up while mailing or
    parsing runs on it without either side affecting the other.

    Two-stage plan (see day_index/stage on the account_warmup row):
      Stage 1 (days 1-10): day 1-2 silent (dialog list only), day 3-5 adds
      channel subscriptions + feed reading + reactions, day 6-10 adds
      chat joins + story viewing.
      Stage 2 (ongoing): 15-20 actions/day — feed reading, reactions,
      online/offline status, optional mutual ping between the same bot
      user's own other warmed-up accounts.

    Gated to paid subscriptions only (see PARSER_GATED_CALLBACKS-style
    gating in SubscriptionMiddleware for the UI side) — an enabled row for
    a free-tier user is simply skipped every tick until they pay, not
    disabled, so it resumes on its own once the subscription is active.
    """

    def __init__(self, db: Database, userbot_manager):
        self.db = db
        self.userbot_manager = userbot_manager
        self._dialog_times: dict[int, list] = {}   # warming account_id -> monotonic start times of its chats
        self._pair_refs: dict = {}  # warmup pair -> dialogs keeping it silenced
        self._dialog_partners: dict[int, dict] = {}  # warming account_id -> {partner_id: last chat time}
        self._frozen: dict[int, float] = {}  # account_id -> wall time until it's skipped (Telegram froze it)
        self._day_index: dict[int, int] = {}  # account_id -> its current warmup day (for the ramp-up)
        self._pair_topics: dict[str, tuple[float, list]] = {}
        self._bot_visits: dict[int, dict] = {}  # account_id -> {bot username: wall time of the last visit}
        self._own_bot_due: dict[int, float] = {}  # account_id -> wall time of its next /start to our own bot  # "lo-hi" account ids -> (wall time, topics of their last chat)
        self._dialog_busy: dict[int, int] = {}  # account_id -> chats it's in now
        self._dialog_active: set = set()  # frozenset of the two account ids chatting now
        self._dialog_tasks: set = set()
        self._dialog_progress: dict = {}  # "lo-hi" -> where a running chat is in its script (survives restarts)
        self._resume_queue: list = []     # chats cut off by the last restart, picked up after start
        self._stopping = False
        self._task: Optional[asyncio.Task] = None
        from .warmup_groups import WarmupGroups
        self.groups = WarmupGroups(self)
        from .warmup_voices import WarmupVoices
        self.voices = WarmupVoices(db)
        from .warmup_calls import WarmupCalls
        self.calls = WarmupCalls(db)
        from .warmup_photos import WarmupPhotos
        self.photos = WarmupPhotos(db)

    async def start(self):
        if self._task and not self._task.done():
            return
        try:
            await self.groups.ensure()  # so their messages are ignored from the start
        except Exception as e:
            logger.warning(f"Warmup groups: init failed: {e}")
        await self._restore_state()
        self._task = asyncio.create_task(self._loop())
        self._own_bot_task = asyncio.create_task(self._own_bot_loop())

    async def _own_bot_loop(self):
        """Every connected account (warming or not) /starts our own bot about
        once every 10 days, in the daytime. A new account's first visit lands at
        a random point of its first 10 days, so they don't all come at once."""
        await asyncio.sleep(600)  # clients connect first
        while True:
            try:
                now = time.time()
                hour = now_moscow().hour
                if not (_WARMUP_NIGHT_START_HOUR <= hour < _WARMUP_NIGHT_END_HOUR):
                    async with self.db._conn.execute(("SELECT id FROM accounts WHERE is_active = 1 ORDER BY user_id, id" if self.db.is_pg else "SELECT id FROM accounts WHERE is_active = 1")) as cur:
                        ids = [r[0] for r in await cur.fetchall()]
                    done = 0
                    for aid in ids:
                        due = self._own_bot_due.get(aid)
                        if due is None:
                            self._own_bot_due[aid] = now + random.uniform(0, 10 * 86400)
                            continue
                        if due > now or done >= 5 or self.is_frozen(aid):
                            continue
                        client = self.userbot_manager._clients.get(aid)
                        if not client or not client.is_connected():
                            continue  # only accounts that are connected anyway
                        try:
                            await client.send_message(_bot_username, "/start")
                            self._own_bot_due[aid] = now + random.uniform(9, 11) * 86400
                        except (FloodWaitError, PeerFloodError):
                            self._own_bot_due[aid] = now + 86400
                        except Exception as e:
                            self.note_error(aid, e)
                            self._own_bot_due[aid] = now + 86400
                            logger.debug(f"Own bot /start failed for account {aid}: {e}")
                        done += 1
                        await asyncio.sleep(random.uniform(20, 90))
                    alive = set(ids)
                    for aid in [a for a in self._own_bot_due if a not in alive]:
                        self._own_bot_due.pop(aid, None)
                    await self._save_state()
            except asyncio.CancelledError:
                raise
            except Exception as e:
                logger.warning(f"Own bot visits: {type(e).__name__}: {e}")
            await asyncio.sleep(1200)

    def is_frozen(self, account_id: int) -> bool:
        return self._frozen.get(account_id, 0) > time.time()

    def note_error(self, account_id, e) -> bool:
        """A frozen account can't chat — keep it out of warmup chats and
        groups for a day (then it's tried again). Returns True if frozen."""
        if account_id is not None and _FROZEN_ACCOUNT_MARKER in str(e).lower():
            if not self.is_frozen(account_id):
                logger.info(f"Warmup: account {account_id} is frozen by Telegram — out of chats for 24h")
            self._frozen[account_id] = time.time() + 86400
            return True
        return False

    async def _save_state(self):
        """Daily chat counters and partner history used to reset on restart
        (an account could then start another 10 chats the same day)."""
        from .state_store import mono_to_wall, save_state
        now = time.monotonic()
        await save_state(self.db, "warmup.dialogs", {
            "times": {str(a): [mono_to_wall(t) for t in ts if now - t < 86400]
                      for a, ts in self._dialog_times.items() if ts},
            "partners": {str(a): {str(p): mono_to_wall(t) for p, t in ps.items()}
                         for a, ps in self._dialog_partners.items() if ps},
            "frozen": {str(a): round(t) for a, t in self._frozen.items() if t > time.time()},
            "pair_topics": {k: [round(v[0]), v[1]] for k, v in self._pair_topics.items()
                            if time.time() - v[0] < 7 * 86400},
            "bot_visits": {str(a): {b: round(t) for b, t in v.items()} for a, v in self._bot_visits.items() if v},
            "own_bot_due": {str(a): round(t) for a, t in self._own_bot_due.items()},
        })
        await save_state(self.db, "warmup.progress", [
            v for v in self._dialog_progress.values() if time.time() - v["ts"] < 3600])
        await self.groups.save_state()

    async def _restore_state(self):
        from .state_store import load_state, wall_to_mono
        try:
            st = await load_state(self.db, "warmup.dialogs", {}) or {}
            for a, ts in (st.get("times") or {}).items():
                self._dialog_times[int(a)] = [wall_to_mono(t) for t in ts]
            for a, ps in (st.get("partners") or {}).items():
                self._dialog_partners[int(a)] = {int(p): wall_to_mono(t) for p, t in ps.items()}
            self._frozen.update({int(a): t for a, t in (st.get("frozen") or {}).items()})
            self._pair_topics.update({k: (v[0], v[1]) for k, v in (st.get("pair_topics") or {}).items()})
            self._bot_visits.update({int(a): dict(v) for a, v in (st.get("bot_visits") or {}).items()})
            self._own_bot_due.update({int(a): t for a, t in (st.get("own_bot_due") or {}).items()})
            self._resume_queue = [v for v in (await load_state(self.db, "warmup.progress", []) or [])
                                  if time.time() - v.get("ts", 0) < 3600]
            await self.groups.restore_state()
        except Exception as e:
            logger.warning(f"Warmup state restore failed: {e}")

    async def stop(self):
        self._stopping = True  # chats dying with the clients now keep their place for the restart
        own = getattr(self, "_own_bot_task", None)
        if own and not own.done():
            own.cancel()
        if self._task and not self._task.done():
            self._task.cancel()
            try:
                await self._task
            except asyncio.CancelledError:
                pass
        await self._save_state()

    async def _loop(self):
        # Clients connect in the background at startup — a tick right away
        # marked every due account "no_client" and pushed it back an hour.
        await asyncio.sleep(180)
        try:
            await self._resume_dialogs()
        except Exception as e:
            logger.warning(f"Warmup: resuming chats failed: {e}")
        if not self.groups._cleaned:
            # Every start, at any hour (it used to wait for the daytime group
            # hours): groups get muted + archived again and checked.
            self.groups._cleaned = True
            self.groups._spawn(self.groups.cleanup_clientless())
            self.groups._spawn(self.groups.rehide_all())
        while True:
            try:
                await self._tick()
            except asyncio.CancelledError:
                raise
            except Exception as e:
                logger.error(f"Warmup service tick failed: {e}", exc_info=True)
            await asyncio.sleep(_WARMUP_CHECK_INTERVAL)

    async def _tick(self):
        try:
            account_ids = await self.db.get_enabled_warmup_account_ids()
        except Exception as e:
            logger.error(f"Warmup: failed to list enabled accounts: {e}")
            return
        for account_id in account_ids:
            try:
                await self._process_account(account_id)
            except Exception as e:
                logger.warning(f"Warmup: account {account_id} failed: {e}")
            await self._save_state()  # writes only when something changed
            await asyncio.sleep(random.uniform(0.5, 2.0))  # stagger connections, same reasoning as elsewhere

    async def _process_account(self, account_id: int):
        warmup = await self.db.get_warmup(account_id)
        if not warmup or not warmup.enabled:
            return
        now = now_moscow()
        if warmup.next_action_at and warmup.next_action_at > now:
            return

        if _WARMUP_NIGHT_START_HOUR <= now.hour < _WARMUP_NIGHT_END_HOUR:
            wake_at = now.replace(hour=_WARMUP_NIGHT_END_HOUR, minute=random.randint(0, 59), second=0, microsecond=0)
            if wake_at <= now:
                wake_at += timedelta(days=1)
            await self.db.record_warmup_action(account_id, "night_pause", wake_at)
            return

        account = await self.db.get_account(account_id)
        if not account or not account.is_active:
            return
        user = await self.db.get_user_by_id(account.user_id)
        if not user or Database.is_free_ad_active(user) or not user.subscription_end or user.subscription_end < now:
            # Paid-only feature — leave it enabled and just wait, it resumes by itself once paid again.
            await self.db.record_warmup_action(account_id, "not_paid", now + timedelta(hours=1))
            return

        # flood_wait_until is a shared account-level flag also set/read by
        # MailingService/ParserService/UserbotManager — a FloodWait on this
        # account from mailing must pause warmup too (it's the same Telegram
        # account-wide restriction), not just the system that triggered it.
        flood_until = await self.db.get_flood_wait_until(account_id)
        if flood_until and flood_until > now:
            await self.db.record_warmup_action(account_id, "flood_wait", flood_until)
            return

        client = await self.userbot_manager.get_client(account_id)
        if not client:
            await self.db.record_warmup_action(account_id, "no_client", now + timedelta(hours=1))
            return

        # Counted from when the account came into the bot or warmup was
        # switched on, whichever is earlier — an account that's been in the
        # bot for a day+ goes straight to the full warmup.
        # Derived from the immutable started_at, not from last_action_at:
        # night_pause/not_paid/no_client/flood_wait/error all legitimately
        # overwrite last_action_at too (see record_warmup_action — that's
        # what lets warmup_view show "Последнее действие: ночная пауза"
        # instead of going stale), so a day-boundary check keyed off
        # last_action_at's date got "used up" by whichever skip event
        # happened to land first each day, before any real stage-1 action
        # ever ran — silently stalling or delaying day_index advancement.
        # started_at is only ever touched by enable_warmup, so this stays
        # correct no matter how many skip ticks happen in between.
        start = warmup.started_at
        if account.created_at and (not start or account.created_at < start):
            start = account.created_at
        days_elapsed = (now.date() - start.date()).days + 1 if start else 1
        if days_elapsed > _WARMUP_STAGE1_TOTAL_DAYS:
            stage, day_index = 2, days_elapsed
        else:
            stage, day_index = 1, days_elapsed
        self._day_index[account_id] = day_index

        try:
            if stage == 1:
                action, delay, did_join = await self._run_stage1(client, warmup, day_index)
                subscribed = did_join and day_index <= 5
                joined = did_join and day_index > 5
            else:
                action, delay, joined = await self._run_stage2(client, account, warmup, day_index)
                subscribed = False
        except (FloodWaitError, PeerFloodError) as e:
            # PeerFloodError carries no duration (it's Telegram's generic
            # "you're spamming" block, not a timed wait) — use the same
            # fallback cooldown MailingService/ParserService use for it.
            wait_s = getattr(e, "seconds", None) or config.PEER_FLOOD_COOLDOWN_SECONDS
            wait_until = now + timedelta(seconds=min(wait_s, 21600))
            try:
                await self.db.set_flood_wait_until(account_id, wait_until)
            except Exception:
                pass
            await self.db.record_warmup_action(
                account_id, "flood_wait", wait_until, stage=stage, day_index=day_index,
            )
            return
        except Exception as e:
            self.note_error(account_id, e)
            logger.warning(f"Warmup: action failed for account {account_id}: {e}")
            await self.db.record_warmup_action(
                account_id, "error", now + timedelta(hours=random.uniform(2, 4)), stage=stage, day_index=day_index,
            )
            return

        await self.db.record_warmup_action(
            account_id, action, now + delay, stage=stage, day_index=day_index, joined=joined, subscribed=subscribed,
        )

    # === Stage runners — each returns (action_type, next_delay, did_join) ===

    async def _run_stage1(self, client, warmup: AccountWarmup, day_index: int):
        if day_index <= 2:
            await self._act_list_dialogs(client)
            return "list_dialogs", timedelta(hours=random.uniform(20, 30)), False

        now = now_moscow()
        can_join_today = not warmup.last_join_at or warmup.last_join_at.date() < now.date()
        pool = ["read_feed", "reaction"]
        if can_join_today:
            pool.append("join_channel")
        if day_index >= 6:
            pool.append("view_stories")
        action = random.choice(pool)
        did_join = False
        if action == "join_channel":
            did_join = await self._act_join_channel(client)
            if not did_join:
                action = "read_feed"
                await self._act_read_feed(client)
        elif action == "read_feed":
            await self._act_read_feed(client)
        elif action == "reaction":
            await self._act_reaction(client)
        elif action == "view_stories":
            await self._act_view_stories(client)
        return action, timedelta(hours=random.uniform(3, 7)), did_join

    async def _run_stage2(self, client, account: Account, warmup=None, day_index: int = 99):
        # A chat with a pool account is tried on every action (it's gated:
        # daytime, up to 10 a day, not while one is running) and runs in the
        # background; otherwise one of the regular actions.
        if day_index >= _WARMUP_GROUPS_FROM_DAY and await self.groups.act(account, client):
            return "group_chat", timedelta(hours=random.uniform(16 / 20, 16 / 15)), False
        if await self._act_mutual_ping(account, client):
            return "mutual_ping", timedelta(hours=random.uniform(16 / 20, 16 / 15)), False
        pool = ["read_feed", "read_feed", "read_feed", "reaction", "reaction", "status_toggle", "status_toggle",
                "view_stories", "view_stories", "saved_note", "vote_poll", "search_channels", "tidy_chats"]
        if day_index >= _WARMUP_VOICES_FROM_DAY:
            pool.append("bot_visit")
        now = now_moscow()
        if (warmup is not None and day_index <= _WARMUP_JOIN_DAYS
                and (not warmup.last_join_at or warmup.last_join_at.date() < now.date())):
            pool += ["join_channel", "join_channel"]
        action = random.choice(pool)
        if action == "join_channel":
            if await self._act_join_channel(client):
                return action, timedelta(hours=random.uniform(16 / 20, 16 / 15)), True
            action = "read_feed"
        if action == "read_feed":
            await self._act_read_feed(client)
        elif action == "reaction":
            await self._act_reaction(client)
        elif action == "status_toggle":
            await self._act_status_toggle(client)
        elif action == "view_stories":
            await self._act_view_stories(client)
        elif action == "saved_note":
            action = await saved_note(client)
        elif action == "vote_poll":
            if not await vote_poll(client):
                action = "read_feed"
                await self._act_read_feed(client)
        elif action == "search_channels":
            may_join = warmup is not None and (not warmup.last_join_at or warmup.last_join_at.date() < now.date())
            if await search_channels(client, may_join):
                return "join_channel", timedelta(hours=random.uniform(16 / 20, 16 / 15)), True
        elif action == "bot_visit":
            bot = await self._pick_bot(account)
            if bot and await visit_bot(client, bot):
                self._bot_visits.setdefault(account.id, {})[bot] = time.time()
            else:
                action = "read_feed"
                await self._act_read_feed(client)
        elif action == "tidy_chats":
            ours = {str(c.get("username") or "").lstrip("@").lower() for c in await self.db.get_warmup_channels()}
            await tidy_chats(client, ours)
        # 15-20 actions a day: 08:00-24:00 is 16 waking hours, so a gap of
        # 16/20 h (48 min) to 16/15 h (64 min) between actions.
        return action, timedelta(hours=random.uniform(16 / 20, 16 / 15)), False

    # === Individual actions — each is best-effort; callers only care about FloodWait/PeerFlood ===

    async def _act_list_dialogs(self, client):
        await client.get_dialogs(limit=50)

    async def _act_read_feed(self, client):
        """Scroll through a chat — mostly channels, where the post views get
        counted like the app does; "typing" only where one can type."""
        dialogs = await client.get_dialogs(limit=30)
        if not dialogs:
            return
        channels = [d for d in dialogs if getattr(d.entity, "broadcast", False)]
        dialog = random.choice(channels if channels and random.random() < 0.6 else dialogs)
        try:
            msgs = await client.get_messages(dialog.input_entity, limit=random.randint(5, 15))
            await asyncio.sleep(random.uniform(4, 15))  # reading
            if getattr(dialog.entity, "broadcast", False):
                await count_views(client, dialog.input_entity, [m.id for m in msgs if m])
            await client.send_read_acknowledge(dialog.input_entity)
        except (FloodWaitError, PeerFloodError):
            raise
        except Exception as e:
            logger.debug(f"Warmup read_feed skipped for a dialog: {e}")

    async def _pick_bot(self, account) -> Optional[str]:
        """A bot this account hasn't visited for 3+ days."""
        visits = self._bot_visits.get(account.id, {})
        now = time.time()
        options = [b for b in BOT_SAFE_BUTTONS if now - visits.get(b, 0) > 3 * 86400]
        return random.choice(options) if options else None

    async def _act_reaction(self, client):
        """React to a fresh post/message in one of the account's channels or
        groups. It used to always pick the first such dialog — when that chat
        had reactions off (or limited), the account never reacted at all."""
        dialogs = await client.get_dialogs(limit=40)
        chats = [d for d in dialogs if not d.is_user]
        random.shuffle(chats)
        if random.random() < 0.7:  # mostly channel posts
            chats.sort(key=lambda d: not getattr(getattr(d, "entity", None), "broadcast", False))
        for dialog in chats[:4]:
            try:
                messages = await client.get_messages(dialog.input_entity, limit=10)
            except (FloodWaitError, PeerFloodError):
                raise
            except Exception as e:
                logger.debug(f"Warmup reaction: couldn't fetch messages: {e}")
                continue
            candidates = [m for m in messages if m and not m.out and not m.action]
            if candidates and await react(client, dialog.input_entity, random.choice(candidates).id):
                return


    async def _act_join_channel(self, client) -> bool:
        channels = await self.db.get_warmup_channels()
        if not channels:
            return False
        ch = random.choice(channels)
        username = str(ch["username"])
        try:
            # Admin can paste a private invite link (t.me/+hash or the older
            # t.me/joinchat/hash form) as well as a plain @username — those
            # need ImportChatInviteRequest instead of JoinChannelRequest,
            # same distinction ParserService.join_chats() makes.
            if username.startswith("+"):
                await client(ImportChatInviteRequest(username.lstrip("+")))
            elif "joinchat/" in username:
                await client(ImportChatInviteRequest(username.split("joinchat/")[-1]))
            else:
                target = username if username.startswith("@") else f"@{username}"
                await client(JoinChannelRequest(target))
            return True
        except UserAlreadyParticipantError:
            return True
        except (FloodWaitError, PeerFloodError):
            raise
        except InviteRequestSentError:
            return False
        except Exception as e:
            logger.warning(f"Warmup: failed to join {username}: {e}")
            return False

